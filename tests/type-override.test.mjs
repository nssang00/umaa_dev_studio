import assert from 'node:assert/strict';
import { seedWorkspace } from '../src/model/seed.js';
import { upgradeWorkspace } from '../src/model/workspaceSchema.js';
import { editTypeField, editTypeDefinition, restoreTypeMock } from '../src/model/typeEditing.js';
import { effectiveTypeFields } from '../src/model/mockIdlCatalog.js';
import { generateComponentFiles } from '../src/logic/codegen.js';
const seed=structuredClone(seedWorkspace);
const pose=seed.messages.find(x=>x.name==='GlobalPoseReportType');
const status=seed.dataTypes.find(x=>x.name==='UMAAStatus');
assert.ok(pose&&status);
assert.equal(seed.messages.length,32);
assert.equal(seed.dataTypes.length,17);
assert.equal(pose.fields.length,11);
let edit=editTypeField(seed,'message',pose.id,'add',{name:'testConfidence',type:'double',optional:true});
assert.ok(edit);
let current=edit.messages.find(x=>x.id===pose.id);
assert.equal(current.projectOverride,true);
assert.equal(current.fields.length,12);
assert.equal(current.mockBaseline.fields.length,11);
assert.equal(pose.fields.length,11,'canonical model was mutated');
assert.equal(editTypeField(edit,'message',pose.id,'add',{name:'timeStamp',type:'DateTime'}),null,'inherited field cannot be duplicated');
assert.equal(editTypeField(edit,'message',pose.id,'add',{name:'bad',type:'double',key:true,optional:true}),null);
edit=editTypeField(edit,'message',pose.id,'update',{originalName:'testConfidence',name:'testConfidence',type:'float',key:false,optional:false});
assert.equal(edit.messages.find(x=>x.id===pose.id).fields.at(-1).type,'float');
edit=upgradeWorkspace(JSON.parse(JSON.stringify(edit)));
assert.equal(edit.messages.find(x=>x.id===pose.id).fields.length,12,'migration must preserve overridden mock fields');
assert.equal(edit.messages.find(x=>x.id===pose.id).projectOverride,true);
const renamed=editTypeDefinition(edit,'message',pose.id,{name:'GlobalPoseReportProjectType',baseType:pose.baseType});
assert.ok(renamed);
assert.equal(renamed.messages.find(x=>x.id===pose.id).name,'GlobalPoseReportProjectType');
let restored=restoreTypeMock(renamed,'message',pose.id);
assert.deepEqual(restored.messages.find(x=>x.id===pose.id).fields,pose.fields);
assert.equal(restored.messages.find(x=>x.id===pose.id).name,pose.name);
assert.ok(!restored.messages.find(x=>x.id===pose.id).projectOverride);
const removed=editTypeField(edit,'message',pose.id,'remove',{originalName:'testConfidence'});
assert.ok(removed);
assert.equal(removed.messages.find(x=>x.id===pose.id).fields.length,11);
const baseCycle=editTypeDefinition(seed,'dataType',status.id,{name:status.name,baseType:`${pose.namespace}::${pose.name}`});
assert.equal(baseCycle,null,'parent cycle rejected');
const renamedBase=editTypeDefinition(seed,'dataType',status.id,{name:'ProjectUMAAStatus',baseType:status.baseType});
assert.ok(renamedBase);
assert.equal(renamedBase.messages.find(x=>x.id===pose.id).baseType,'UMAA::ProjectUMAAStatus');
assert.equal(upgradeWorkspace(renamedBase).messages.find(x=>x.id===pose.id).baseType,'UMAA::ProjectUMAAStatus','dependent type reference persisted through migration');
const statusEdit=editTypeField(seed,'dataType',status.id,'add',{name:'localDebug',type:'boolean'});
assert.equal(effectiveTypeFields(statusEdit,statusEdit.messages.find(x=>x.id===pose.id)).some(x=>x.name==='localDebug'),true);
console.log('PASS editable ICD mock fields; project overrides persist, revert and preserve inheritance');

const generated=generateComponentFiles(edit,'autopilot');
const overrideFile=generated.find(f=>f.path==='contracts/type-overrides.json');
assert.ok(overrideFile);
assert.ok(JSON.parse(overrideFile.content).types.some(t=>t.name==='GlobalPoseReportType'));
assert.ok(!generated.some(f=>f.path.endsWith('GlobalPoseReportType.idl')),'official mock override must not be compiled as standard IDL');
assert.ok(!generated.some(f=>f.path.endsWith('UMAAStatus.idl')),'standard common types must not be emitted as project types');
console.log('PASS generated override manifest is separate from official IDL and TypeSupport');
