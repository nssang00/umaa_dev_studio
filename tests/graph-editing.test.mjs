import assert from 'node:assert/strict';
import { seedWorkspace } from '../src/model/seed.js';
import { serviceContractGraph, typeDependencyGraph, validateCustomContractLink } from '../src/logic/editorGraphs.js';
const s=structuredClone(seedWorkspace);
const gv=s.services.find(x=>x.name==='GlobalVectorControl');
const g=serviceContractGraph(s,gv.id);
assert.equal(g.nodes.filter(n=>n.kind==='operation').length,s.operations.filter(o=>o.serviceId===gv.id).length);
assert.equal(g.nodes.filter(n=>n.kind==='topic').length,4);
assert.equal(g.nodes.filter(n=>n.kind==='type').length,4);
assert.equal(validateCustomContractLink(s,gv.id,'action:fake','topic:fake'),null);
console.log('PASS: Official GlobalVectorControl Contract Graph operation→action→4 Topic→Type projections are read only');
const sampleService={id:'svc-custom-demo',name:'DemoStatus',namespace:'ProjectCustom::DemoStatus',functionalArea:'CUSTOM',source:'custom'};
s.services.push(sampleService);
s.messages.push({id:'m-a',name:'ReportA',namespace:sampleService.namespace,source:'custom',fields:[{name:'sample',type:'long'}]});
s.messages.push({id:'m-b',name:'ReportB',namespace:sampleService.namespace,source:'custom',fields:[]});
s.topics.push({id:'t-a',name:'TopicA',messageTypeId:'m-a'});
s.topics.push({id:'t-b',name:'TopicB',messageTypeId:'m-b'});
s.operations.push({id:'o-a',serviceId:sampleService.id,name:'reportDemo',topicId:'t-a',action:'publish',actor:'provider'});
assert.deepEqual(validateCustomContractLink(s,sampleService.id,'action:o-a','topic:t-b'),{kind:'operation-topic',operationId:'o-a',topicId:'t-b'});
assert.deepEqual(validateCustomContractLink(s,sampleService.id,'topic:t-a','type:m-b'),{kind:'topic-type',topicId:'t-a',typeId:'m-b'});
s.messages.push({id:'m-x',name:'Other',namespace:'Elsewhere',source:'custom',fields:[]});
assert.equal(validateCustomContractLink(s,sampleService.id,'topic:t-a','type:m-x'),null);
const t=typeDependencyGraph(s,'message','m-a');
assert.equal(t.nodes.filter(n=>n.kind==='field').length,1);
assert.equal(t.edges.length,1);
console.log('PASS: Custom graph links enforce same namespace; Type field graph is derived from model');
