import assert from 'node:assert/strict';
import { seedWorkspace } from '../src/model/seed.js';
import { upgradeWorkspace } from '../src/model/workspaceSchema.js';
import { parseWorkspaceImport } from '../src/model/validateImport.js';
import { deriveEndpoints } from '../src/logic/endpoints.js';
import { generateComponentFiles } from '../src/logic/codegen.js';
import { validateWorkspace } from '../src/logic/validation.js';
const s = structuredClone(seedWorkspace);
assert.equal(s.functionalAreas.filter(a=>a.source==='standard').length,8);
assert.equal(s.dataTypes.length,17);
assert.equal(s.qosProfiles[0].name,'Project Default');
assert.equal(s.componentRuntime.autopilot.domainId,0);
const custom={ id:'custom-s1',name:'CustomSensorStatus',namespace:'ProjectCustom::CustomSensorStatus',functionalArea:'SA',source:'custom',version:'1.0',flowControl:'request-reply',description:'test'};
s.services.push(custom);
s.interfaces.push({id:'if-custom',serviceId:custom.id,name:'Custom Interface',operationIds:['op-report','op-query']});
s.messages.push({id:'type-custom',name:'CustomSensorReportType',namespace:custom.namespace,source:'custom',fields:[{name:'value',type:'double',key:false,optional:false}]});
s.topics.push({id:'topic-custom',name:'CustomSensorReportType',messageTypeId:'type-custom'});
s.operations.push({id:'op-report',serviceId:custom.id,name:'reportCustomSensor',topicId:'topic-custom',action:'publish',actor:'provider'});
s.operations.push({id:'op-query',serviceId:custom.id,name:'queryCustomSensor',topicId:'topic-custom',action:'subscribe',actor:'consumer'});
s.components.push({id:'sensor',name:'SensorFusion'});
s.componentRuntime.sensor={domainId:12,partition:'alpha',qosProfileId:'qos-project-default',commandArbitration:'user-implementation',hostMode:'isolated-process'};
s.bindings.push({id:'sensor-p',componentId:'sensor',serviceId:custom.id,role:'provider'},{id:'autopilot-c',componentId:'autopilot',serviceId:custom.id,role:'consumer'});
s.connections.push({id:'custom-conn',providerBindingId:'sensor-p',consumerBindingId:'autopilot-c'});
assert.equal(deriveEndpoints(s,'sensor').find(e=>e.serviceName===custom.name).direction,'writer');
assert.equal(deriveEndpoints(s,'autopilot').find(e=>e.serviceName===custom.name).direction,'reader');
assert.deepEqual(validateWorkspace(s).filter(i=>i.severity==='error'),[]);
const files=generateComponentFiles(s,'sensor'), get=p=>files.find(f=>f.path===p)?.content;
assert.equal(JSON.parse(get('config/dds-profile.json')).domainId,12);
assert.equal(JSON.parse(get('config/runtime.json')).hostMode,'isolated-process');
assert.equal(JSON.parse(get('contracts/communication-patterns.json')).contracts[0].template,'request-reply');
assert(get('idl/custom/CustomSensorReportType.idl').includes('struct CustomSensorReportType'));
assert(get('include/component_api.h').includes('umaa_component_abi_version'));
const legacy=structuredClone(seedWorkspace);delete legacy.qosProfiles;delete legacy.componentRuntime;delete legacy.dataTypes;
const upgraded=parseWorkspaceImport(legacy);
assert(upgraded.componentRuntime.autopilot);
assert.equal(upgraded.qosProfiles.length,1);
assert.equal(upgraded.dataTypes.length,17);
assert.equal(upgradeWorkspace(upgraded).qosProfiles.length,1);
console.log('PASS Standard 8 FA read-only metadata + custom-service cross-area binding');
console.log('PASS Topic/Type/Operation → P/C Reader/Writer projection, runtime settings + C ABI skeleton');
console.log('PASS Legacy workspace migration + generated runtime contract + custom IDL');
