import assert from 'node:assert/strict';
import { seedWorkspace } from '../src/model/seed.js';
import { categoryForService, categoryLabel, flowLabel, operationPurpose, serviceFlowProjection, isLargeCollection, isSpecialization } from '../src/model/icdConcepts.js';
import { canCreateTopic,canCreateTopicRelation,canAssignServiceCategory,isQosAncestor } from '../src/model/assetRules.js';
import { validateWorkspace } from '../src/logic/validation.js';
import { generateComponentFiles } from '../src/logic/codegen.js';
const s=structuredClone(seedWorkspace);
const globalVector=s.services.find(x=>x.name==='GlobalVectorControl');
const globalPose=s.services.find(x=>x.name==='GlobalPoseStatus');
assert.equal(categoryForService(globalVector),'control');
assert.equal(categoryLabel(globalPose),'Status / Report');
assert.equal(flowLabel(globalPose.flowControl),'Request / Reply');
assert.equal(operationPurpose({name:'reportGlobalVectorCommandStatus'}),'Status Report Operation');
assert.equal(operationPurpose({name:'reportGlobalVectorCommandAck'}),'Command Ack Report Operation');
const vector=serviceFlowProjection(s,globalVector.id);
assert.ok(vector.reports.length>0 && vector.commands.length>0);
assert.ok(vector.disposes.some(o=>o.name.startsWith('cancel')));
assert.ok(vector.queries.every(o=>o.action==='subscribe'));
assert.ok(!canAssignServiceCategory(s,globalVector.id,'status-report'),'standard service is immutable');
assert.ok(canAssignServiceCategory({...s,services:[{...globalVector,source:'custom'}]},globalVector.id,'status-report'));
assert.equal(isLargeCollection(s.topicRelations[0]),true);
assert.equal(isSpecialization({kind:'specialization'}),true);
const independentType={id:'type-standalone',name:'MyReportType',namespace:'ProjectCustom::Types',source:'custom',fields:[{name:'value',type:'double'}]};
s.messages.push(independentType);
assert.ok(canCreateTopic(s,'MyReportTopic',independentType.id));
assert.equal(canCreateTopic(s,'Bad Topic',independentType.id),false);
assert.equal(canCreateTopic(s,'MyReportTopic',s.messages.find(m=>m.source==='standard').id),false);
s.topics.push({id:'project-topic-a',name:'MyReportTopic',namespace:'ProjectCustom::Types',source:'custom',messageTypeId:independentType.id});
s.topics.push({id:'project-topic-b',name:'MyReportElement',namespace:'ProjectCustom::Types',source:'custom',messageTypeId:independentType.id});
assert.ok(canCreateTopicRelation(s,'large-list-element','project-topic-a','project-topic-b'));
assert.ok(canCreateTopicRelation(s,'specialization','project-topic-a','project-topic-b'));
assert.equal(canCreateTopicRelation(s,'large-set-element','project-topic-a','project-topic-a'),false);
assert.equal(canCreateTopicRelation(s,'large-set-element','project-topic-a',seedWorkspace.topics[0].id),false);
s.topicRelations.push({id:'project-large-list',kind:'large-list-element',parentTopicId:'project-topic-a',relatedTopicId:'project-topic-b',source:'custom'});
assert.ok(validateWorkspace(s).some(x=>x.code==='COLLECTION_SYNC_TODO'&&x.entityId==='project-large-list'));
s.topicRelations.push({id:'project-specialization',kind:'specialization',parentTopicId:'project-topic-a',relatedTopicId:'project-topic-b',source:'custom'});
assert.ok(validateWorkspace(s).some(x=>x.code==='SPECIALIZATION_SYNC_TODO'));
const q=[{id:'root',baseProfileId:null},{id:'child',baseProfileId:'root'},{id:'grandchild',baseProfileId:'child'}];
assert.equal(isQosAncestor(q,'child','root'),false);
assert.equal(isQosAncestor(q,'root','grandchild'),true);
const files=generateComponentFiles(s,'autopilot');
assert.ok(files.some(x=>x.path==='contracts/icd-patterns.json'));
assert.ok(files.some(x=>x.path==='contracts/project-assets.json'));
assert.ok(files.some(x=>x.path==='contracts/type-overrides.json'));
assert.ok(!files.some(x=>x.path.startsWith('idl/standard/')&&x.path.endsWith('.idl')),'no official IDL fabrication');
console.log('PASS: ICD category vs flow control, Report operation, independent Topic/Data Type, pattern warnings, QoS base, generation metadata');
